import { mkdir, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { SuggestionView } from '@awp/protocol';
import { repoKey } from './match';

const KIND_TITLE: Record<string, string> = {
  mcp: 'MCP servers and connectors',
  connector: 'MCP servers and connectors',
  plugin: 'Plugins',
  skill: 'Skills',
  library: 'Libraries',
  tool: 'Tools',
};
const KIND_ORDER = [
  'MCP servers and connectors',
  'Plugins',
  'Skills',
  'Libraries',
  'Tools',
];

const line = (v: SuggestionView) => {
  const it = v.item;
  const repo = repoKey(it.source.repo);
  const sha = it.source.sha ? ` @ \`${it.source.sha.slice(0, 7)}\`` : '';
  const bits = [
    `**${it.name}** (\`${v.id}\`)`,
    v.verified ? null : '**unverified**',
    `license: ${it.license}`,
    repo ? `source: ${repo}${sha}` : null,
    v.notPinned ? 'not pinned (Claude Code installs the latest)' : null,
    it.flags.telemetry ? 'sends telemetry' : null,
    it.flags.writes ? 'can change things in your accounts' : null,
  ].filter(Boolean);
  const out = [`- ${bits.join(' · ')}`];
  if (v.reason) out.push(`  - Why: ${v.reason}`);
  if (v.command) out.push(`  - Command: \`${v.command}\``);
  for (const n of it.flags.notes) out.push(`  - Note: ${n}`);
  if (v.error) out.push(`  - Problem: ${v.error}`);
  if (it.neverStages.length)
    out.push(
      `  - Use in build phases only, not in ${it.neverStages.join(', ')}.`,
    );
  return out.join('\n');
};

/** `docs/TOOLING.md`: what was approved, installed, failed, rejected or left as an idea. */
export function renderTooling(items: SuggestionView[]): string {
  const head = [
    '# Tooling',
    '',
    '<!-- Generated by AWP from your Connectors decisions. Edits here are overwritten; change decisions in AWP. -->',
    '',
  ];
  const real = items.filter((v) => !v.idea);
  const installed = real.filter(
    (v) =>
      v.status === 'installed' && (v.action !== 'doc' || v.via === 'terminal'),
  );
  const manual = real.filter(
    (v) =>
      v.status === 'installed' && v.action === 'doc' && v.via !== 'terminal',
  );
  const pending = real.filter(
    (v) => v.status === 'approved' || v.status === 'failed',
  );
  const ideas = items.filter((v) => v.idea && v.status !== 'rejected');
  const rejected = items.filter((v) => v.status === 'rejected');

  if (
    !installed.length &&
    !manual.length &&
    !pending.length &&
    !ideas.length &&
    !rejected.length
  )
    return `${head.join('\n')}Nothing has been approved yet.\n`;

  const out = [...head];
  if (installed.length) {
    out.push('## Installed', '');
    const byTitle = new Map<string, SuggestionView[]>();
    for (const v of installed) {
      const t = KIND_TITLE[v.item.kind] ?? 'Other';
      byTitle.set(t, [...(byTitle.get(t) ?? []), v]);
    }
    for (const t of KIND_ORDER)
      if (byTitle.has(t))
        out.push(`### ${t}`, '', ...(byTitle.get(t) ?? []).map(line), '');
  }
  if (manual.length) {
    out.push(
      '## To install yourself',
      '',
      'Recorded here; AWP does not run these. Libraries are installed by the build phase that needs them.',
      '',
      ...manual.map(line),
      '',
    );
  }
  if (pending.length)
    out.push('## Approved, not installed yet', '', ...pending.map(line), '');
  if (ideas.length)
    out.push(
      '## Ideas to add yourself',
      '',
      'Suggested by the recommender; AWP has nothing to install for these.',
      '',
      ...ideas.map(
        (v) =>
          `- **${v.item.name}**${v.category ? ` (${v.category})` : ''}: ${v.reason}`,
      ),
      '',
    );
  if (rejected.length)
    out.push(
      '## Rejected',
      '',
      'AWP will not suggest these again.',
      '',
      ...rejected.map(
        (v) =>
          `- **${v.item.name}** (\`${v.id}\`)${v.reason && v.reason !== 'Default for new projects.' ? `: ${v.reason}` : ''}`,
      ),
      '',
    );
  return `${out.join('\n').trimEnd()}\n`;
}

export async function writeTooling(
  root: string,
  items: SuggestionView[],
): Promise<void> {
  const dir = join(root, 'docs');
  await mkdir(dir, { recursive: true });
  const file = join(dir, 'TOOLING.md');
  const tmp = `${file}.${process.pid}.tmp`;
  await writeFile(tmp, renderTooling(items));
  await rename(tmp, file);
}
