import { existsSync, mkdirSync, mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { RegistryFile, type SuggestionView } from '@awp/protocol';
import { expect, test } from 'vitest';
import { bundledRegistry } from './load';
import { renderTooling, writeTooling } from './tooling-md';

const reg = bundledRegistry();
const view = (
  id: string,
  status: SuggestionView['status'],
  over: Partial<SuggestionView> = {},
): SuggestionView => {
  const item = reg.items.find((i) => i.id === id);
  if (!item) throw new Error(id);
  return {
    id,
    source: 'registry',
    verified: true,
    idea: false,
    alternatives: [],
    status,
    reason: `Because ${id}.`,
    at: '2026-10-19T00:00:00.000Z',
    item,
    license: { status: 'ok', note: item.license },
    missingSecrets: [],
    action: item.install.type === 'skill' ? 'preview' : item.install.type,
    notPinned: false,
    ...over,
  } as SuggestionView;
};

test('groups installed items by kind with source, license and why', () => {
  const md = renderTooling([
    view('context7', 'installed'),
    view('ponytail', 'installed', { notPinned: true }),
    view('graphify', 'installed'),
  ]);
  expect(md).toContain('# Tooling');
  expect(md).toContain('## Installed');
  expect(md).toContain('### MCP servers and connectors');
  expect(md).toMatch(/\*\*Context7\*\* \(`context7`\)/);
  expect(md).toContain('Because context7.');
  expect(md).toContain('MIT');
  expect(md).toContain('github.com/upstash/context7');
  expect(md).toContain('84740e3'); // pinned commit, short
  expect(md).toMatch(/not pinned/i);
});

test('libraries and tools approved for later are listed with their command', () => {
  const md = renderTooling([
    view('lenis', 'installed', { action: 'doc', command: 'npm i lenis' }),
    view('caveman', 'installed', {
      action: 'doc',
      command: 'npx @caveman-ai/cli@latest',
    }),
  ]);
  expect(md).toContain('## To install yourself');
  expect(md).toContain('`npm i lenis`');
  expect(md).toContain('`npx @caveman-ai/cli@latest`');
  // the "never in these stages" rule is stated
  expect(md).toMatch(/not in .*ideation/i);
});

test('failed, approved-but-not-installed, ideas and rejected items get their own sections', () => {
  const md = renderTooling([
    view('stripe', 'approved'),
    view('aws', 'failed', { error: 'uvx is not installed' }),
    view('supabase', 'rejected', { reason: 'using Firebase' }),
    {
      ...view('context7', 'suggested'),
      id: 'security-reviewer',
      idea: true,
      source: 'recommender',
      verified: false,
      category: 'Subagents',
      reason: 'Reviews auth code.',
    } as SuggestionView,
  ]);
  expect(md).toContain('## Approved, not installed yet');
  expect(md).toContain('uvx is not installed');
  expect(md).toContain('## Ideas to add yourself');
  expect(md).toContain('Reviews auth code.');
  expect(md).toContain('## Rejected');
  expect(md).toContain('using Firebase');
});

test('unverified items are marked, and no secrets or tokens can appear', () => {
  const md = renderTooling([
    {
      ...view('context7', 'installed'),
      id: 'acme',
      source: 'recommender',
      verified: false,
      item: RegistryFile.parse({
        version: 1,
        items: [
          {
            id: 'acme',
            kind: 'mcp',
            name: 'Acme',
            summary: 's',
            license: 'unknown',
            verified: false,
            source: {},
            install: { type: 'doc', command: 'claude mcp add acme' },
          },
        ],
      }).items[0],
    } as SuggestionView,
  ]);
  expect(md).toMatch(/unverified/i);
  expect(md).not.toMatch(/Bearer\s+\S{8,}/);
});

test('an empty list says so', () => {
  expect(renderTooling([])).toContain('Nothing has been approved yet');
});

test('writeTooling writes docs/TOOLING.md atomically and leaves other docs alone', async () => {
  const root = mkdtempSync(join(tmpdir(), 'awp-tl-'));
  mkdirSync(join(root, 'docs'), { recursive: true });
  await writeTooling(root, [view('context7', 'installed')]);
  const text = readFileSync(join(root, 'docs', 'TOOLING.md'), 'utf8');
  expect(text).toContain('Context7');
  expect(text).toMatch(/generated by AWP/i);
  expect(existsSync(join(root, 'docs', 'TOOLING.md.tmp'))).toBe(false);
});

test('a library or tool that was run in the terminal is listed as installed, not as "to install yourself"', () => {
  const ran = view('lenis', 'installed', {
    action: 'doc',
    command: 'npm i lenis',
    via: 'terminal',
  } as never);
  const recorded = view('caveman', 'installed', {
    action: 'doc',
    command: 'npx @caveman-ai/cli@latest',
  });
  const md = renderTooling([ran, recorded]);
  expect(md).toContain('### Libraries');
  expect(md).toContain('## To install yourself');
  const manual = md.split('## To install yourself')[1];
  expect(manual).toContain('Caveman');
  expect(manual).not.toContain('Lenis');
});
